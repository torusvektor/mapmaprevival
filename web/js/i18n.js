const DICTS = { cs, en };
let current = 'en';
const missing = new Set();

export function detectLanguage() {
  const langs = navigator.languages || [navigator.language || 'en'];
  for (const l of langs) {
    const code = String(l).toLowerCase().slice(0, 2);
    if (DICTS[code]) return code;
    if (code === 'sk') return 'cs';
  }
  return 'en';
}

export function setLanguage(lang) {
  current = lang && lang !== 'auto' && DICTS[lang] ? lang : detectLanguage();
  document.documentElement.lang = current;
}

export function getLanguage() { return current; }

export function t(key, params = {}) {
  let v = DICTS[current][key];
  if (v === undefined) v = en[key];
  if (v === undefined) {
    if (!missing.has(key)) { missing.add(key); console.warn('Missing translation', key); }
    return key;
  }
  if (typeof v === 'function') return v(params);
  return v.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m));
}

/**
 * Applies translations to elements with data-i18n (text) and data-i18n-title (title/aria-label).
 * shortcutFor(key) may return a shortcut shown in titles.
 */
export function applyI18n(root, shortcutFor = () => '') {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    const key = el.dataset.i18nTitle;
    const sc = shortcutFor(key);
    el.title = sc ? `${t(key)} (${sc})` : t(key);
    el.setAttribute('aria-label', t(key));
  }
}

export function missingTranslations() { return [...missing]; }
